LANGUAGES = {"uk": {**UK, **DESKTOP_UK}, "en": {**EN, **DESKTOP_EN}}
LOCALE_UNITS = {"uk": ["Б", "КБ", "МБ", "ГБ"], "en": ["B", "KB", "MB", "GB"]}

_lang = "uk"


def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in LANGUAGES else "uk"


def language() -> str:
    return _lang


def tr(key: str, **params) -> str:
    text = LANGUAGES[_lang].get(key) or LANGUAGES["uk"].get(key) or key
    for name, value in params.items():
        text = text.replace("{" + name + "}", str(value))
    return text


def describe_code(code: str | None) -> str:
    """Translated text for an error code (e.g. from a rollback report)."""
    if code and f"error.{code}" in LANGUAGES["uk"]:
        return tr(f"error.{code}")
    return tr("error.not_restored")


def describe_error(exc: BaseException | None) -> str:
    """User-facing, translated description; raw backend text is never shown."""
    code = getattr(exc, "code", None)
    if isinstance(code, str) and f"error.{code}" in LANGUAGES["uk"]:
        extra = getattr(exc, "extra", None) or {}
        return tr(f"error.{code}", min=extra.get("password_min_length", 6))
    status = getattr(exc, "status_code", None)
    if status is not None:
        if status == 0:
            return tr("error.network_error")
        if status == 401:
            return tr("error.session_expired")
        if status == 403:
            return tr("error.forbidden")
        if status == 404:
            return tr("error.not_found")
        if status in (400, 422):
            return tr("error.validation_error")
        if status >= 500:
            return tr("error.server")
    if isinstance(exc, PermissionError):
        return tr("error.local_permission_denied")
    if isinstance(exc, FileNotFoundError):
        return tr("error.local_not_found")
    if isinstance(exc, OSError):
        return tr("error.local_io_error")
    return tr("error.generic")


# --- formatting --------------------------------------------------------------------------


def format_size(size: int | None) -> str:
    if size is None:
        return "-"
    units = LOCALE_UNITS[_lang]
    value = float(size)
    unit = 0
    while value >= 1024 and unit < len(units) - 1:
        value /= 1024
        unit += 1
    if unit == 0:
        return f"{int(value)} {units[0]}"
    text = f"{value:.1f}" if value < 10 else f"{value:.0f}"
    if _lang == "uk":
        text = text.replace(".", ",")
    return f"{text} {units[unit]}"


def format_datetime(value: str | None, short: bool = False) -> str:
    """ISO timestamp from the API → local time, compact numeric form (07.10.2026, 14:05:09)."""
    if not value:
        return "-"
    try:
        moment = datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone()
    except ValueError:
        return value
    if _lang == "en":
        return moment.strftime("%d/%m, %H:%M:%S" if short else "%d/%m/%Y, %H:%M:%S")
    return moment.strftime("%d.%m, %H:%M:%S" if short else "%d.%m.%Y, %H:%M:%S")
