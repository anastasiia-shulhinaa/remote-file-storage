"""Copies the web client's texts (web/src/i18n/messages.ts) into the desktop client.

Both clients therefore show exactly the same Ukrainian/English wording.
Run after changing the web texts:   python scripts/sync_i18n.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "web" / "src" / "i18n" / "messages.ts"
TARGET = ROOT / "desktop" / "app" / "i18n_messages.py"

ENTRY = re.compile(r'^\s*"([^"]+)":\s*("(?:[^"\\]|\\.)*"),\s*$')


def block(text: str, start: str, end: str) -> dict[str, str]:
    body = text[text.index(start) + len(start):]
    body = body[: body.index(end)]
    result = {}
    for line in body.splitlines():
        match = ENTRY.match(line)
        if match:
            result[match.group(1)] = json.loads(match.group(2))
    return result


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    uk = block(text, "export const uk = {", "} as const;")
    en = block(text, "export const en: Record<MessageKey, string> = {", "\n};")
    missing = set(uk) ^ set(en)
    if missing:
        raise SystemExit(f"uk/en keys differ: {sorted(missing)}")
    lines = [
        '"""Generated by scripts/sync_i18n.py from web/src/i18n/messages.ts (do not edit)."""',
        "",
        "UK = " + json.dumps(uk, ensure_ascii=False, indent=4, sort_keys=True),
        "",
        "EN = " + json.dumps(en, ensure_ascii=False, indent=4, sort_keys=True),
        "",
    ]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(uk)} texts -> {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
